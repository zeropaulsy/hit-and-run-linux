#include <pddi/gl/glshaders.hpp>

//-----------------------------------------------------------------------------
// Direct3D 8's fixed-function pipeline as the D3D8 pddi configured it
//-----------------------------------------------------------------------------

// Lighting follows Direct3D 8's equations: per vertex, in eye space, normals renormalised (NORMALIZENORMALS), a local
// viewer (LOCALVIEWER's default), light ambient terms 0 (the pddi's lights have none; the ambient is global), material
// colours from the material, never the vertex (COLORVERTEX with every source D3DMCS_MATERIAL), specular only with a
// shininess > 0 (SPECULARENABLE), point lights cut off at their range. Eye space here is OpenGL's (z negated, see
// pglContext::LoadHardwareMatrix): x and y, and so lighting and the reflection vector's x and y, are D3D's.
// Fog distance is |eye z|, as D3D's linear table fog. Each program's source is compiled with a header defining
// REFLECTION and REFRACTION 0 or 1.
const char* const pglVertexDeclarations =
    "#ifdef PVK\n"
    "#define PVK_LOCATION(n) layout(location = n)   // Vulkan: as the GL renderer binds them (PGL_ATTRIB_*)\n"
    "#else\n"
    "#define PVK_LOCATION(n)\n"
    "#endif\n"
    "PVK_LOCATION(0) in vec3 aPosition;\n"
    "PVK_LOCATION(1) in vec3 aNormal;\n"
    "PVK_LOCATION(2) in vec4 aColour;\n"
    "PVK_LOCATION(3) in vec2 aUV;\n"
    "uniform mat4 uProjection;\n"
    "uniform mat4 uModelView;\n"
    "uniform mat3 uNormalMatrix;\n"
    "uniform bool uLit;\n"
    "uniform vec4 uMatAmbient;\n"
    "uniform vec4 uMatDiffuse;\n"
    "uniform vec4 uMatSpecular;\n"
    "uniform vec4 uMatEmissive;\n"
    "uniform float uShininess;\n"
    "uniform vec4 uGlobalAmbient;\n"
    "uniform int uLightCount;\n"
    "uniform vec4 uLightPosition[8];\n"
    "uniform vec3 uLightColour[8];\n"
    "uniform vec3 uLightAtten[8];\n"
    "uniform float uLightRange[8];\n"
    "out vec4 vColour;\n"
    "out vec3 vSpecular;\n"
    "out vec2 vUV;\n"
    "#if REFLECTION\n"
    "out vec2 vReflectionUV;\n"
    "#endif\n"
    "#if CUSTOM\n"
    "uniform float uTime;\n"
    "uniform vec2 uResolution;\n"
    "// the position as the game places it, in clip space\n"
    "vec4 StandardPosition(vec3 position)\n"
    "{\n"
    "    return uProjection * (uModelView * vec4(position, 1.0));\n"
    "}\n"
    "out vec3 vNormal;\n"
    "out vec3 vEyePosition;\n"
    "#elif REFRACTION\n"
    "out vec3 vNormal;\n"
    "#endif\n"
    "out float vFogDistance;\n"
    "#ifdef PVK_SUN\n"
    "uniform mat4 uEyeToWorld;\n"
    "out vec3 vSunOffset;     // world space, from the camera\n"
    "out vec3 vSunNormal;\n"
    "#endif\n";

const char* const pglVertexMain =
    "void main()\n"
    "{\n"
    "    vec4 eye = uModelView * vec4(aPosition, 1.0);\n"
    "#if MATERIAL_VERTEX\n"
    "    gl_Position = MaterialVertex(aPosition, aNormal);\n"
    "#else\n"
    "    gl_Position = uProjection * eye;\n"
    "#endif\n"
    "#ifdef PVK\n"
    "    gl_Position.z = (gl_Position.z + gl_Position.w) * 0.5;   // Vulkan: depth 0..1, not -1..1\n"
    "    gl_PointSize = 1.0;     // GL's default; Vulkan points need it written\n"
    "#endif\n"
    "    vUV = aUV;\n"
    "    vFogDistance = abs(eye.z);\n"
    "    vec3 v = eye.xyz / eye.w;\n"
    "    vec3 n = uNormalMatrix * aNormal;\n"
    "    float nLength = length(n);\n"
    "    if(nLength > 0.0)\n"
    "        n /= nLength;\n"
    "#if CUSTOM || REFRACTION\n"
    "    vNormal = n;\n"
    "#endif\n"
    "#if CUSTOM\n"
    "    vEyePosition = v;\n"
    "#endif\n"
    "#if REFLECTION\n"
    "    // D3DTSS_TCI_CAMERASPACEREFLECTIONVECTOR through the shader's texture matrix: (0.5 x + 0.5, 0.5 - 0.5 y)\n"
    "    vec3 r = reflect(normalize(v), n);\n"
    "    vReflectionUV = vec2(0.5 * r.x + 0.5, 0.5 - 0.5 * r.y);\n"
    "#endif\n"
    "#ifdef PVK_SUN\n"
    "    vSunOffset = mat3(uEyeToWorld) * v;\n"
    "    vSunNormal = mat3(uEyeToWorld) * n;\n"
    "#endif\n"
    "    if(!uLit)\n"
    "    {\n"
    "        vColour = aColour;\n"
    "        vSpecular = vec3(0.0);\n"
    "        return;\n"
    "    }\n"
    "    vec3 toEye = -normalize(v);\n"
    "    vec3 colour = uMatEmissive.rgb + uMatAmbient.rgb * uGlobalAmbient.rgb;\n"
    "    vec3 specular = vec3(0.0);\n"
    "    for(int i = 0; i < uLightCount; i++)\n"
    "    {\n"
    "        vec3 l;\n"
    "        float attenuation = 1.0;\n"
    "        if(uLightPosition[i].w == 0.0)\n"
    "        {\n"
    "            l = normalize(uLightPosition[i].xyz);\n"
    "        }\n"
    "        else\n"
    "        {\n"
    "            vec3 d = uLightPosition[i].xyz / uLightPosition[i].w - v;\n"
    "            float distance = length(d);\n"
    "            if(distance > uLightRange[i])\n"
    "                continue;\n"
    "            l = d / distance;\n"
    "            attenuation = 1.0 / (uLightAtten[i].x + uLightAtten[i].y * distance + uLightAtten[i].z * distance * distance);\n"
    "        }\n"
    "        float nl = dot(n, l);\n"
    "        colour += attenuation * max(nl, 0.0) * uMatDiffuse.rgb * uLightColour[i];\n"
    "        if(uShininess > 0.0 && nl > 0.0)\n"
    "        {\n"
    "            float nh = max(dot(n, normalize(l + toEye)), 0.0);\n"
    "            specular += attenuation * pow(nh, uShininess) * uMatSpecular.rgb * uLightColour[i];\n"
    "        }\n"
    "    }\n"
    "    vColour = clamp(vec4(colour, uMatDiffuse.a), 0.0, 1.0);\n"
    "    vSpecular = clamp(specular, 0.0, 1.0);\n"
    "}\n";

// The texture stages (simple: diffuse * texture; reflection: that plus envBlend * reflection map, saturated), then
// the specular sum, linear fog (RGB only) and the alpha test (pddiCompareMode order). A stage without a texture
// passes its colour through, as D3D's did.
const char* const pglFragmentPrelude =
    "in vec4 vColour;\n"
    "in vec3 vSpecular;\n"
    "in vec2 vUV;\n"
    "#if REFLECTION\n"
    "in vec2 vReflectionUV;\n"
    "uniform bool uReflectionTextured;\n"
    "uniform sampler2D uReflection;\n"
    "uniform vec4 uEnvBlend;\n"
    "#endif\n"
    "#if REFRACTION\n"
    "in vec3 vNormal;\n"
    "uniform sampler2D uScreen;\n"
    "uniform vec4 uRefractColour;\n"
    "uniform float uRefractIndex;\n"
    "uniform float uRefractBlend;\n"
    "uniform vec2 uResolution;\n"
    "#endif\n"
    "#if CUSTOM\n"
    "in vec3 vNormal;\n"
    "in vec3 vEyePosition;\n"
    "uniform bool uLit;\n"
    "uniform vec4 uMatAmbient;\n"
    "uniform vec4 uMatDiffuse;\n"
    "uniform vec4 uMatSpecular;\n"
    "uniform vec4 uMatEmissive;\n"
    "uniform float uShininess;\n"
    "uniform vec4 uGlobalAmbient;\n"
    "uniform int uLightCount;\n"
    "uniform vec4 uLightPosition[8];\n"
    "uniform vec3 uLightColour[8];\n"
    "uniform vec3 uLightAtten[8];\n"
    "uniform float uLightRange[8];\n"
    "uniform float uTime;\n"
    "uniform vec2 uResolution;\n"
    "#endif\n"
    "in float vFogDistance;\n"
    "uniform bool uTextured;\n"
    "uniform sampler2D uTexture;\n"
    "uniform bool uFog;\n"
    "uniform vec3 uFogColour;\n"
    "uniform float uFogEnd;\n"
    "uniform float uFogScale;\n"
    "uniform int uAlphaCompare;\n"
    "uniform float uAlphaRef;\n"
    "uniform bool uAlphaToCoverage;\n"
    "uniform float uMipAlpha;\n"
    "out vec4 fragColour;\n"
    "// the base texture; with mipmapping on (uMipAlpha: the anisotropy), an alpha-tested texture's alpha is raised\n"
    "// with the mip level sampled, so averaged-down levels keep the coverage (fences and leaves would thin out)\n"
    "vec4 SampleBase()\n"
    "{\n"
    "    vec4 t = texture(uTexture, vUV);\n"
    "    if(uMipAlpha > 0.0 && (uAlphaCompare == 4 || uAlphaCompare == 5))\n"
    "    {\n"
    "        vec2 size = vec2(textureSize(uTexture, 0));\n"
    "        vec2 dx = dFdx(vUV * size);\n"
    "        vec2 dy = dFdy(vUV * size);\n"
    "        float major = max(dot(dx, dx), dot(dy, dy));\n"
    "        float minor = max(min(dot(dx, dx), dot(dy, dy)), 1e-8);\n"
    "        float lod = 0.5 * log2(max(major, 1e-8)) - log2(min(sqrt(major / minor), uMipAlpha));\n"
    "        t.a *= 1.0 + max(lod, 0.0) * 0.25;\n"
    "    }\n"
    "    return t;\n"
    "}\n"
    "// the material as the game draws it, before fog\n"
    "vec4 StandardColour()\n"
    "{\n"
    "    vec4 c = vColour;\n"
    "    if(uTextured)\n"
    "        c *= SampleBase();\n"
    "#if REFLECTION\n"
    "    vec4 e = uEnvBlend;\n"
    "    if(uReflectionTextured)\n"
    "        e *= texture(uReflection, vReflectionUV);\n"
    "    c = min(c + e, 1.0);\n"
    "#endif\n"
    "    c.rgb = min(c.rgb + vSpecular, 1.0);\n"
    "#if REFRACTION\n"
    "    // the screen behind, its position moved by the normal (screen y down on the PS2 and Xbox), times the\n"
    "    // refraction colour, over the material by uRefractBlend (1 on the PS2; the Xbox's crossfade), opaque\n"
    "#ifdef PVK\n"
    "    vec2 offset = vec2(vNormal.x, vNormal.y) * uRefractIndex * (uResolution.y / 448.0);   // Vulkan: gl_FragCoord y down\n"
    "#else\n"
    "    vec2 offset = vec2(vNormal.x, -vNormal.y) * uRefractIndex * (uResolution.y / 448.0);\n"
    "#endif\n"
    "    vec2 uv = clamp((gl_FragCoord.xy + offset) / uResolution, vec2(0.0), vec2(1.0));\n"
    "    c = vec4(mix(c.rgb, texture(uScreen, uv).rgb * uRefractColour.rgb, uRefractBlend), 1.0);\n"
    "#endif\n"
    "    return c;\n"
    "}\n"
    "#if CUSTOM\n"
    "// the base texture (white without one)\n"
    "vec4 BaseTexture()\n"
    "{\n"
    "    return uTextured ? SampleBase() : vec4(1.0);\n"
    "}\n"
    "// eye-space direction from this pixel towards light i (< uLightCount), and its attenuation (0 out of range)\n"
    "vec3 LightVector(int i, out float attenuation)\n"
    "{\n"
    "    attenuation = 1.0;\n"
    "    if(uLightPosition[i].w == 0.0)\n"
    "        return normalize(uLightPosition[i].xyz);\n"
    "    vec3 d = uLightPosition[i].xyz / uLightPosition[i].w - vEyePosition;\n"
    "    float distance = length(d);\n"
    "    attenuation = distance > uLightRange[i] ? 0.0 :\n"
    "        1.0 / (uLightAtten[i].x + uLightAtten[i].y * distance + uLightAtten[i].z * distance * distance);\n"
    "    return d / max(distance, 1e-6);\n"
    "}\n"
    "// the game's lighting (Direct3D 8's equations) at this pixel for normal n (eye space, normalised): emissive +\n"
    "// ambient + each light's diffuse part, returned; its highlights (materials with a shininess) in specular. wrap > 0\n"
    "// lets light reach further round the surface (softer shading: (n.l + wrap) / (1 + wrap)).\n"
    "vec3 Lighting(vec3 n, float wrap, out vec3 specular)\n"
    "{\n"
    "    vec3 toEye = -normalize(vEyePosition);\n"
    "    vec3 colour = uMatEmissive.rgb + uMatAmbient.rgb * uGlobalAmbient.rgb;\n"
    "    specular = vec3(0.0);\n"
    "    for(int i = 0; i < uLightCount; i++)\n"
    "    {\n"
    "        float attenuation;\n"
    "        vec3 l = LightVector(i, attenuation);\n"
    "        float nl = dot(n, l);\n"
    "        float diffuse = max((nl + wrap) / (1.0 + wrap), 0.0);\n"
    "        colour += attenuation * diffuse * uMatDiffuse.rgb * uLightColour[i];\n"
    "        if(nl > 0.0 && uShininess > 0.0)\n"
    "            specular += attenuation * pow(max(dot(n, normalize(l + toEye)), 0.0), uShininess) * uMatSpecular.rgb * uLightColour[i];\n"
    "    }\n"
    "    return colour;\n"
    "}\n"
    "#endif\n"
    "#ifdef PVK_SUN\n"
    "// Vulkan, SHAR_SUN (vk/vksun.hpp): the sun on this pixel. Pre-lit colours go between the shadow and sunlit\n"
    "// levels by n.l and a ray towards the sun, lit ones (the game lit them) only darken where the ray is blocked.\n"
    "in vec3 vSunOffset;\n"
    "in vec3 vSunNormal;\n"
    "uniform mat4 uEyeToWorld;\n"
    "uniform vec3 uSunDirection;    // world space, towards the sun\n"
    "uniform vec4 uSun;             // x: 0 none, 1 pre-lit, 2 lit; y, z: pre-lit shadow, sunlit; w: lit shadow\n"
    "uniform vec2 uSunSoft;         // the sun disc's radius (tangent), rays per pixel\n"
    "uniform vec3 uSunRange;        // full rays to x (one at 2x), no shadow past y (faded from 0.8y), ray length z\n"
    "layout(binding = 5) uniform accelerationStructureEXT uSunScene;\n"
    "// alpha-tested casters (instance custom index = row): UV and triangle offsets in sunGeometry, mask | compare\n"
    "// << 16, alpha ref; the masks (64x64 alpha bytes each); the casters' UVs and triangles\n"
    "layout(std430, binding = 6) readonly buffer SunCasters { uvec4 sunCaster[]; };\n"
    "layout(std430, binding = 7) readonly buffer SunMasks { uint sunMask[]; };\n"
    "layout(std430, binding = 8) readonly buffer SunGeometry { uint sunGeometry[]; };\n"
    "vec2 SunUV(uint base, uint vertex)\n"
    "{\n"
    "    return vec2(uintBitsToFloat(sunGeometry[base + vertex * 2u]), uintBitsToFloat(sunGeometry[base + vertex * 2u + 1u]));\n"
    "}\n"
    "// whether a candidate hit on an alpha-tested caster is where its alpha test passes\n"
    "bool SunOpaque(int caster, int primitive, vec2 b)\n"
    "{\n"
    "    uvec4 c = sunCaster[caster];\n"
    "    uint t = c.y + uint(primitive) * 3u;\n"
    "    vec2 uv = SunUV(c.x, sunGeometry[t]) * (1.0 - b.x - b.y) + SunUV(c.x, sunGeometry[t + 1u]) * b.x +\n"
    "              SunUV(c.x, sunGeometry[t + 2u]) * b.y;\n"
    "    uvec2 texel = uvec2(ivec2(floor(fract(uv) * 64.0)) & 63);\n"
    "    uint i = (c.z & 0xffffu) * 4096u + texel.y * 64u + texel.x;\n"
    "    float alpha = float((sunMask[i >> 2] >> ((i & 3u) * 8u)) & 255u) / 255.0;\n"
    "    float ref = uintBitsToFloat(c.w);\n"
    "    return (c.z >> 16) == 4u ? alpha > ref : alpha >= ref;\n"
    "}\n"
    "// one ray towards the sun: -1 if it gets through, else the blocker's id\n"
    "int SunRay(vec3 origin, vec3 direction, bool litDraw)\n"
    "{\n"
    "    rayQueryEXT q;\n"
    "    rayQueryInitializeEXT(q, uSunScene, gl_RayFlagsTerminateOnFirstHitEXT, litDraw ? 0x01 : 0xff, origin,\n"
    "                          0.01, direction, uSunRange.z);\n"
    "    while(rayQueryProceedEXT(q))\n"
    "    {\n"
    "        // only alpha-tested casters come here: the rest are opaque\n"
    "        if(SunOpaque(rayQueryGetIntersectionInstanceCustomIndexEXT(q, false),\n"
    "                     rayQueryGetIntersectionPrimitiveIndexEXT(q, false),\n"
    "                     rayQueryGetIntersectionBarycentricsEXT(q, false)))\n"
    "            rayQueryConfirmIntersectionEXT(q);\n"
    "    }\n"
    "    if(rayQueryGetIntersectionTypeEXT(q, true) == gl_RayQueryCommittedIntersectionNoneEXT)\n"
    "        return -1;\n"
    "    return rayQueryGetIntersectionInstanceCustomIndexEXT(q, true);\n"
    "}\n"
    "vec3 SunShade(vec3 c)\n"
    "{\n"
    "    vec3 face = cross(dFdx(vSunOffset), dFdy(vSunOffset));\n"
    "    if(uSun.x == 0.0)\n"
    "        return c;\n"
    "    float faceLength = length(face);\n"
    "    face = faceLength > 0.0 ? face / faceLength : vec3(0.0, 1.0, 0.0);\n"
    "    if(dot(face, vSunOffset) > 0.0)\n"
    "        face = -face;          // the side facing the camera (winding is unreliable)\n"
    "    vec3 n = vSunNormal;\n"
    "    float nLength = length(n);\n"
    "    n = nLength > 0.0 ? n / nLength : face;\n"
    "    if(dot(n, face) < 0.0)\n"
    "        n = -n;\n"
    "    if(dot(n, face) < 0.7)\n"
    "        n = face;              // a crease (a box's corner): the polygon's own\n"
    "    float nl = dot(n, uSunDirection);\n"
    "    bool litDraw = uSun.x > 1.5;  // the game lit it: only the world's shadow on it (not its own: mask)\n"
    "    float distance = length(vSunOffset);\n"
    "    // far away (fogged, a few pixels per metre) the shadow fades out and no rays are traced\n"
    "    float fade = uSunRange.y > 0.0 ? smoothstep(0.8 * uSunRange.y, uSunRange.y, distance) : 0.0;\n"
    "    bool traced = (nl > 0.0 || litDraw) && fade < 1.0;\n"
    "    vec3 origin = uEyeToWorld[3].xyz + vSunOffset + face * (0.03 + 0.002 * distance);\n"
    "    // soft shadows: rays spread over the sun's disc (a spiral turned per pixel), the share that gets through\n"
    "    vec3 t = normalize(cross(abs(uSunDirection.y) < 0.99 ? vec3(0.0, 1.0, 0.0) : vec3(1.0, 0.0, 0.0), uSunDirection));\n"
    "    vec3 s = cross(uSunDirection, t);\n"
    "    int rays = int(abs(uSunSoft.y));\n"
    "    // the full count to uSunRange.x, falling to one at twice that\n"
    "    if(uSunRange.x > 0.0)\n"
    "        rays = max(min(rays, 1), int(mix(float(rays), 1.0, clamp(distance / uSunRange.x - 1.0, 0.0, 1.0)) + 0.5));\n"
    "    if(uSunSoft.y < 0.0)    // SHAR_SUN_DEBUG: the blocker's id\n"
    "    {\n"
    "        int id = traced ? SunRay(origin, uSunDirection, litDraw) : -1;\n"
    "        if(id >= 0)\n"
    "            return vec3(float(uint(id) & 255u), float((uint(id) >> 8) & 255u), 255.0) / 255.0;\n"
    "        rays = 0;\n"
    "    }\n"
    "    float lit = 0.0;\n"
    "    int count = 0;\n"
    "#ifdef PVK_SUN_QUAD\n"
    "    // each pixel of the 2x2 quad traces every 4th ray of the spiral (turned per quad), the quad shares the sums: the\n"
    "    // full count at a quarter of the cost, the shadow at half resolution. Outside branches: every pixel of the quad\n"
    "    // has to reach the broadcasts (helper pixels off the triangle trace too)\n"
    "    vec2 sum = vec2(0.0);       // clear, traced\n"
    "    if(traced)\n"
    "    {\n"
    "        uint corner = gl_SubgroupInvocationID & 3u;\n"
    "        float turn = 6.2831853 * fract(52.9829189 * fract(dot(floor(gl_FragCoord.xy * 0.5), vec2(0.06711056, 0.00583715))));\n"
    "        bool share = rays > 1;  // one ray (hard shadows): each pixel its own\n"
    "        for(int r = share ? int(corner) : 0; r < rays; r += share ? 4 : 1)\n"
    "        {\n"
    "            float radius = sqrt((float(r) + 0.5) / float(rays)) * uSunSoft.x;\n"
    "            float angle = float(r) * 2.3999632 + turn;\n"
    "            vec3 direction = normalize(uSunDirection + (t * cos(angle) + s * sin(angle)) * radius);\n"
    "            sum += vec2(float(SunRay(origin, direction, litDraw) < 0), 1.0);\n"
    "        }\n"
    "    }\n"
    "    vec2 quad = sum + subgroupQuadSwapHorizontal(sum);\n"
    "    quad += subgroupQuadSwapVertical(quad);\n"
    "    if(rays > 1)\n"
    "        sum = quad;\n"
    "    if(traced)\n"
    "        lit = sum.y > 0.0 ? sum.x / sum.y : 1.0;\n"
    "#else\n"
    "    if(traced && rays > 3)\n"
    "    {\n"
    "        // the disc's centre and two opposite rim points first: all clear or all blocked is fully lit or in shade\n"
    "        // (most pixels), only penumbrae trace the rest\n"
    "        float turn = 6.2831853 * fract(52.9829189 * fract(dot(gl_FragCoord.xy, vec2(0.06711056, 0.00583715))));\n"
    "        vec3 rim = (t * cos(turn) + s * sin(turn)) * uSunSoft.x;\n"
    "        lit = float(SunRay(origin, uSunDirection, litDraw) < 0) +\n"
    "              float(SunRay(origin, normalize(uSunDirection + rim), litDraw) < 0) +\n"
    "              float(SunRay(origin, normalize(uSunDirection - rim), litDraw) < 0);\n"
    "        count = 3;\n"
    "        if(lit == 0.0 || lit == 3.0)\n"
    "            rays = 0;\n"
    "    }\n"
    "    if(traced)\n"
    "    {\n"
    "        float turn = 6.2831853 * fract(52.9829189 * fract(dot(gl_FragCoord.xy, vec2(0.06711056, 0.00583715))));\n"
    "        for(int r = 0; r < rays; r++)\n"
    "        {\n"
    "            float radius = sqrt((float(r) + 0.5) / float(rays)) * uSunSoft.x;\n"
    "            float angle = float(r) * 2.3999632 + turn;\n"
    "            vec3 direction = normalize(uSunDirection + (t * cos(angle) + s * sin(angle)) * radius);\n"
    "            lit += float(SunRay(origin, direction, litDraw) < 0);\n"
    "        }\n"
    "        count += rays;\n"
    "        lit = count > 0 ? lit / float(count) : 1.0;\n"
    "    }\n"
    "#endif\n"
    "    lit = mix(lit, 1.0, fade);\n"
    "    if(!litDraw)\n"
    "        return c * (uSun.y + (uSun.z - uSun.y) * lit * max(nl, 0.0));\n"
    "    return c * mix(uSun.w, 1.0, lit);\n"
    "}\n"
    "#endif\n"
    "// fog, then the alpha test\n"
    "void FinishFragment(vec4 c)\n"
    "{\n"
    "    if(uFog)\n"
    "        c.rgb = mix(uFogColour, c.rgb, clamp((uFogEnd - vFogDistance) * uFogScale, 0.0, 1.0));\n"
    "    // alpha-to-coverage (MSAA): instead of the cut, alpha ramps from 0 to 1 over about a pixel around the\n"
    "    // reference, and the hardware covers that share of the pixel's samples\n"
    "    float alphaWidth = max(fwidth(c.a), 1e-4);\n"
    "    if(uAlphaToCoverage)\n"
    "    {\n"
    "        c.a = clamp((c.a - uAlphaRef) / alphaWidth + 0.5, 0.0, 1.0);\n"
    "        if(c.a <= 0.0)\n"
    "            discard;\n"
    "        fragColour = c;\n"
    "        return;\n"
    "    }\n"
    "    bool pass = true;\n"
    "    if(uAlphaCompare == 0) pass = false;\n"
    "    else if(uAlphaCompare == 2) pass = c.a < uAlphaRef;\n"
    "    else if(uAlphaCompare == 3) pass = c.a <= uAlphaRef;\n"
    "    else if(uAlphaCompare == 4) pass = c.a > uAlphaRef;\n"
    "    else if(uAlphaCompare == 5) pass = c.a >= uAlphaRef;\n"
    "    else if(uAlphaCompare == 6) pass = c.a == uAlphaRef;\n"
    "    else if(uAlphaCompare == 7) pass = c.a != uAlphaRef;\n"
    "    if(!pass)\n"
    "        discard;\n"
    "    fragColour = c;\n"
    "}\n";

