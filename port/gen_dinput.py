"""Generate port/compat/dinput.h: the DirectInput 8 constants and data structures the game uses, extracted
from the DX8 SDK header bundled with Pure3D (libs/pure3d/sdks/dx8/dinput.h). No API is generated."""
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "libs/pure3d/sdks/dx8/dinput.h")
OUT = os.path.join(ROOT, "port/compat/dinput.h")

src = open(SRC, encoding="latin-1").read().replace("\r\n", "\n")
lines = src.split("\n")


def struct_block(name):
    m = re.search(r"typedef struct " + re.escape(name) + r"\s*\{.*?\n\}[^;]*;", src, re.S)
    assert m, name
    return m.group(0)


def defines(prefix):
    out, i = [], 0
    while i < len(lines):
        if re.match(r"#define\s+" + prefix, lines[i]):
            out.append(lines[i])
            while lines[i].rstrip().endswith("\\"):
                i += 1
                out.append(lines[i])
        i += 1
    return out


parts = [
    "/* Linux stand-in for <dinput.h>: the DirectInput 8 CONSTANTS and DATA STRUCTURES the game uses to name",
    "   input points (DIK_ key codes, DIJOFS_/DIMOFS_ offsets) and to describe force-feedback effects.",
    "   GENERATED by port/gen_dinput.py from libs/pure3d/sdks/dx8/dinput.h. No DirectInput API is provided:",
    "   devices are read by radcore's SDL2 controller backend (radcontroller/linux/sdlcontroller.cpp). */",
    "#ifndef SHAR_COMPAT_DINPUT_H", "#define SHAR_COMPAT_DINPUT_H", "", '#include "windows.h"', "#include <stddef.h>", "",
    "#ifndef FIELD_OFFSET", "#define FIELD_OFFSET(type, field) ((LONG)offsetof(type, field))", "#endif",
    "typedef LONG* LPLONG;", "",
    "#define DI_FFNOMINALMAX             10000", "#define DI_SECONDS                  1000000", "",
]
for s in ["DICONSTANTFORCE", "DIPERIODIC", "DICONDITION", "DIENVELOPE", "DIEFFECT"]:
    parts += [struct_block(s), ""]
parts += defines("DIEFF_") + defines("DIEB_") + [""]
parts += [struct_block("_DIMOUSESTATE"), "", struct_block("_DIMOUSESTATE2"), ""] + defines("DIMOFS_") + [""]
parts += [struct_block("DIJOYSTATE"), "", struct_block("DIJOYSTATE2"), ""] + defines("DIJOFS_") + [""]
parts += defines("DIK_") + ["", "#endif /* SHAR_COMPAT_DINPUT_H */", ""]
open(OUT, "w").write("\n".join(parts))
print(f"{OUT}: {len(defines('DIK_'))} DIK codes")
